"""
### DBT_DATABRICKS_PIPELINE

Runs the **entire `dbt_databricks` project on Databricks** in dependency order.

**How the graph is built.** The project has ~5,500 models, so one Airflow task per model is not
practical (every dbt call parses the project). Instead there is one task per *domain/layer slice*
(`models/<domain>/<layer>`, plus the `dbt_artifacts` package) and the edges between slices come
straight from the dbt `ref()` graph (`include/Configuration/dbt_databricks_graph.json`, generated by
`include/Python/generate_dbt_databricks_graph.py`). Every cross-slice model dependency is enforced by
an Airflow edge; dbt orders the models *inside* a slice itself. Slices that depend on each other in
both directions (e.g. `teh_finance` silver <-> gold) are merged into one task.

**Execution.** Default: dbt runs from `dbt_venv` on the Airflow worker and sends SQL to the Databricks
SQL warehouse. Set `DBT_EXECUTION_MODE=databricks_job` to submit each slice as a Databricks Jobs
`dbt_task` instead (see `include/Python/dbt_databricks_job_operator.py`).

**Run parameters** (Trigger DAG w/ config)

| param | meaning |
|---|---|
| `dbt_command` | `run` (default), `build` (models + tests) or `test` |
| `select_nodes` | comma list of task ids or domains to run, e.g. `tea_service,teh_finance`; empty = all. Unselected upstream tasks are treated as done. |
| `skip_nodes` | comma list of task ids/domains to skip, e.g. `dbt_artifacts` |
| `full_refresh` | pass `--full-refresh` (rebuilds incremental models) |
| `threads` | dbt threads per task (mind SQL warehouse concurrency) |
| `exclude` | extra dbt `--exclude` selector |
| `dbt_vars` | extra dbt `--vars` as YAML/JSON |
| `fail_fast` | pass `--fail-fast` |
| `use_dbt_retry` | on an Airflow retry, only re-run what failed (`dbt retry`) |
| `skip_preflight` / `strict_graph_check` | see the `preflight` task |

**Deployment variables**: see `DEPLOYMENT_GUIDE.txt` (DATABRICKS_* variables, `DBT_EXECUTION_MODE`,
`DBT_MAX_PARALLEL_NODES`, `DBT_DATABRICKS_PIPELINE_SCHEDULE`).
"""
from __future__ import annotations

import logging
import os
from datetime import timedelta

import pendulum

from include.Python import dbt_databricks_common as C
from include.Python.dbt_databricks_airflow_compat import DAG, EmptyOperator, Param, TaskGroup, TriggerRule, task
from include.Python.dbt_databricks_operators import DbtDatabricksBashOperator

log = logging.getLogger("airflow.task")

EXECUTION_MODE = os.environ.get("DBT_EXECUTION_MODE", "airflow_cli").strip().lower()
MAX_PARALLEL_NODES = int(os.environ.get("DBT_MAX_PARALLEL_NODES", "8"))
NODE_TIMEOUT_HOURS = float(os.environ.get("DBT_NODE_TIMEOUT_HOURS", "6"))
SCHEDULE = os.environ.get("DBT_DATABRICKS_PIPELINE_SCHEDULE") or None  # cron string; None = triggered only
RETRIES = int(os.environ.get("DBT_TASK_RETRIES", "2" if C.IS_PROD else "0"))

GRAPH = C.load_graph()  # small JSON, validated (unique ids, known edges, acyclic)
NODES = {n["id"]: n for n in GRAPH["nodes"]}

if EXECUTION_MODE not in ("airflow_cli", "databricks_job"):
    raise ValueError(f"DBT_EXECUTION_MODE must be 'airflow_cli' or 'databricks_job', got {EXECUTION_MODE!r}")
JOB_CONFIG = None
if EXECUTION_MODE == "databricks_job":
    from include.Python.dbt_databricks_job_operator import DbtDatabricksJobOperator, load_job_config
    JOB_CONFIG = load_job_config()

PARAMS = {
    "dbt_command": Param("run", type="string", enum=["run", "build", "test"],
                         description="run = models only; build = models + tests; test = tests only"),
    "select_nodes": Param("", type="string", description="Comma list of task ids / domains to run (empty = all)"),
    "skip_nodes": Param("", type="string", description="Comma list of task ids / domains to skip"),
    "full_refresh": Param(False, type="boolean", description="dbt --full-refresh"),
    "threads": Param(int(os.environ.get("DBT_THREADS", "4")), type="integer", minimum=1, maximum=64),
    "exclude": Param("", type="string", description="Additional dbt --exclude selector"),
    "dbt_vars": Param("", type="string", description="dbt --vars as YAML/JSON, e.g. {run_date: 2026-01-01}"),
    "fail_fast": Param(False, type="boolean"),
    "use_dbt_retry": Param(True, type="boolean", description="On Airflow retry run `dbt retry` (failed/skipped nodes only)"),
    "skip_preflight": Param(False, type="boolean", description="Bypass pre-flight checks (not recommended)"),
    "strict_graph_check": Param(True, type="boolean", description="Fail (not just warn) when the committed graph is stale"),
}


def _make_node_task(node: dict):
    common = dict(
        task_id=node["task"],
        trigger_rule=TriggerRule.NONE_FAILED,  # an excluded/skipped upstream must not block downstream
        execution_timeout=timedelta(hours=NODE_TIMEOUT_HOURS),
        doc_md=(
            f"**{node['id']}**: {node['models']} models, {node['tests']} tests\n\n"
            f"selector: `{node['selector']}`\n\nsources: {', '.join(node['sources']) or '-'}"
            + ("\n\n_Merged because these slices depend on each other in both directions._" if node["merged_cycle"] else "")
        ),
    )
    if EXECUTION_MODE == "databricks_job":
        return DbtDatabricksJobOperator(
            dbt_node_id=node["id"], dbt_domain=node["group"], select=node["selector"], job_config=JOB_CONFIG, **common
        )
    return DbtDatabricksBashOperator(select=node["selector"], dbt_node_id=node["id"], dbt_domain=node["group"], **common)


with DAG(
    dag_id="DBT_DATABRICKS_PIPELINE",
    description="Dependency-ordered dbt run of the dbt_databricks project on Databricks",
    doc_md=__doc__,
    start_date=pendulum.datetime(2025, 9, 1, tz="America/Chicago"),
    schedule=SCHEDULE,
    catchup=False,
    max_active_runs=1,  # two full runs would race on the same incremental tables
    max_active_tasks=MAX_PARALLEL_NODES,
    params=PARAMS,
    default_args={"owner": "data-platform", "retries": RETRIES, "retry_delay": timedelta(minutes=5)},
    tags=["dbt", "databricks", "dbt_databricks"],
) as dag:

    @task(task_id="preflight", retries=0)
    def preflight(**context):
        from include.Python.dbt_databricks_preflight import run_preflight
        return run_preflight(dict(context["params"]), check_graph_file=True)

    start = preflight()
    end = EmptyOperator(task_id="pipeline_complete", trigger_rule=TriggerRule.NONE_FAILED)

    groups: dict[str, TaskGroup] = {}
    tasks: dict[str, object] = {}
    for node in GRAPH["nodes"]:
        if node["group"] not in groups:  # (setdefault would build a TaskGroup on every iteration)
            groups[node["group"]] = TaskGroup(group_id=node["group"])
        with groups[node["group"]]:
            tasks[node["id"]] = _make_node_task(node)

    has_upstream = {down for _, down in GRAPH["edges"]}
    has_downstream = {up for up, _ in GRAPH["edges"]}
    for up, down in GRAPH["edges"]:
        tasks[up] >> tasks[down]
    for node_id, t in tasks.items():
        if node_id not in has_upstream:
            start >> t
        if node_id not in has_downstream:
            t >> end
